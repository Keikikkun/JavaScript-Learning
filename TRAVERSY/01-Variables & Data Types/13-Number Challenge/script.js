let x = Math.floor(Math.random() * 100 + 1);
let y = Math.floor(Math.random() * 50 + 1);

let sumOutput = x + y;
console.log(`${x} + ${y} = ${sumOutput}`);

let difference = x - y;

console.log(`${x} - ${y} = ${difference}`);

let product = x *y;

console.log(`${x} * ${y} = ${product}`);

let quotient = x / y;

console.log(`${x} / ${y} = ${quotient}`);

let modulo = x % y;

console.log(`${x} % ${y} = ${modulo}`);  